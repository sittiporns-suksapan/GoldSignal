'use strict';

const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getState: () => ipcRenderer.invoke('get-state'),
  getSettings: () => ipcRenderer.invoke('get-settings'),
  saveSettings: (partial) => ipcRenderer.invoke('save-settings', partial),
  listPlugins: () => ipcRenderer.invoke('list-plugins'),
  togglePlugin: (id, enabled) => ipcRenderer.invoke('toggle-plugin', { id, enabled }),
  reloadPlugins: () => ipcRenderer.invoke('reload-plugins'),
  refreshNow: () => ipcRenderer.invoke('refresh-now'),
  openPluginsDir: (which) => ipcRenderer.invoke('open-plugins-dir', which),
  installEa: () => ipcRenderer.invoke('install-ea'),
  eaStatus: () => ipcRenderer.invoke('ea-status'),
  sendOrder: (req) => ipcRenderer.invoke('send-order', req),
  closePosition: (ticket) => ipcRenderer.invoke('close-position', ticket),
  modifyPosition: (req) => ipcRenderer.invoke('modify-position', req),
  sendPending: (req) => ipcRenderer.invoke('send-pending', req),
  cancelPending: (ticket) => ipcRenderer.invoke('cancel-pending', ticket),
  modifyPending: (req) => ipcRenderer.invoke('modify-pending', req),
  getWebUrl: () => ipcRenderer.invoke('get-web-url'),
  webAccessGet: () => ipcRenderer.invoke('web-access-get'),
  webAccessSet: (req) => ipcRenderer.invoke('web-access-set', req),
  webAccessLogoutAll: () => ipcRenderer.invoke('web-access-logout-all'),
  tunnelStart: (provider) => ipcRenderer.invoke('tunnel-start', { provider }),
  tunnelStop: () => ipcRenderer.invoke('tunnel-stop'),
  pagesSetup: (repo) => ipcRenderer.invoke('pages-setup', { repo }),
  tgGet: () => ipcRenderer.invoke('tg-get'),
  tgSet: (p) => ipcRenderer.invoke('tg-set', p),
  tgDetect: (token) => ipcRenderer.invoke('tg-detect', token),
  tgTest: () => ipcRenderer.invoke('tg-test'),
  closeAll: () => ipcRenderer.invoke('close-all'),
  pickBridgeFile: () => ipcRenderer.invoke('pick-bridge-file'),
  reportError: (msg, stack) => ipcRenderer.invoke('client-error', { msg: String(msg).slice(0, 500), stack: String(stack || '').slice(0, 2000) }),
  onSnapshot: (cb) => ipcRenderer.on('snapshot', (_e, snap) => cb(snap)),
  onOrderResult: (cb) => ipcRenderer.on('order-result', (_e, r) => cb(r)),
  onAutoClose: (cb) => ipcRenderer.on('auto-close', (_e, r) => cb(r)),
  getRoundHistory: () => ipcRenderer.invoke('get-round-history'),
  openHistoryWindow: () => ipcRenderer.invoke('open-history-window'),
  onAutoEnter: (cb) => ipcRenderer.on('auto-enter', (_e, r) => cb(r)),
  onTick: (cb) => ipcRenderer.on('tick', (_e, q) => cb(q)),
});